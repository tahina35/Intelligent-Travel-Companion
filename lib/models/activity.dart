class Activity {
  final String name;
  final String type;
  final String description;
  final String distance;
  final String imageUrl;
  final String reason;
  final bool isOpen;
  final double rating;

  Activity({
    required this.name,
    required this.type,
    required this.description,
    required this.distance,
    required this.imageUrl,
    required this.reason,
    required this.isOpen,
    required this.rating,
  });
}
